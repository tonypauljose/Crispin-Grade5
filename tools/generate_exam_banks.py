    def make_mul_3():
        a = random.randint(100, 999)
        b = random.randint(2, 9)
        return Q("fill", f"{fmt(a)} × {b} = ?",
                 answer=[str(a * b), fmt(a * b)],
                 explain=f"{fmt(a)} × {b} = {fmt(a * b)}.")
    qs += take_uniq(make_mul_3, 15)

    # Division (clean)
    def make_div_clean():
        b = random.randint(2, 12)
